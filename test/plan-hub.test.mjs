test("4.2.4: el botón del plan se arrastra, se pega al borde y recuerda el sitio", () => {
  const bloque = app.slice(app.indexOf("const PLAN_FAB_KEY"), app.indexOf("function planFab("));
  assert.match(bloque, /cp-plan-fab/);
  assert.match(bloque, /safe-area-inset-top/);
  assert.match(bloque, /safe-area-inset-right/);
  assert.match(bloque, /safe-area-inset-bottom/);
  assert.match(bloque, /safe-area-inset-left/);
  assert.match(bloque, /\.tabbar/);
  assert.match(bloque, /PLAN_FAB_UMBRAL/);
  assert.match(bloque, /pointerType !== "touch"/);
  assert.match(bloque, /stopPropagation/);
  assert.match(bloque, /lado === "izq" \? box\.minX : box\.maxX/);
  assert.match(estilo, /\.plan-fab \{[^}]*touch-action: none/);
  const fabCss = estilo.slice(estilo.indexOf(".plan-fab {"), estilo.indexOf(".plan-fab__icono"));
  assert.match(fabCss, /border:\s*2\.5px solid var\(--fab-borde\)/);
  assert.match(fabCss, /html\[data-theme="dark"\] \.plan-fab \{ --fab-borde: #1A120C; \}/);
  assert.match(fabCss, /:root:not\(\[data-theme="light"\]\) \.plan-fab \{ --fab-borde: #1A120C; \}/);
  assert.match(fabCss, /\.plan-fab\.is-arrastre:active[\s\S]*0 6px 0 var\(--fab-borde\), 0 14px 28px rgba\(0,0,0,\.5\)/);
  assert.match(fabCss, /@media \(prefers-reduced-motion: reduce\) \{\s*\.plan-fab:active \{ transform: none; \}/);
  assert.match(app, /engancharPlanFab\(\)/);
  const fab = app.slice(app.indexOf("function planFab("), app.indexOf("function renderPlanSheet("));
  assert.match(fab, /htmlMartillo\(40, "plan-fab__icono"\)/);
  assert.equal(fab.includes("<svg"), false);
  const icono = htmlMartillo(40, "plan-fab__icono");
  assert.match(icono, /oficial\/resources\/martillo\.png/);
  assert.match(icono, /draggable="false"/);
  assert.match(icono, /width="1024"/);
  assert.match(icono, /height="1024"/);
  assert.equal(icono.includes("<svg"), false);
  const manifest = JSON.parse(readFileSync(new URL("../assets/manifest.json", import.meta.url), "utf8"));
  const cajas = JSON.parse(readFileSync(new URL("../assets/cajas-alfa.json", import.meta.url), "utf8"));
  const im = manifest.iconos_recurso.martillo;
  assert.equal(im.copia_identica, true);
  assert.ok(im.ancho >= 1024 && im.alto >= 1024);
  const box = cajas[im.ruta];
  const aj = ajusteOf({ ruta: im.ruta, ancho: im.ancho, alto: im.alto }, 40);
  const arte = Math.max(box.w, box.h);
  assert.ok(arte >= arte * aj.escala * DEVICE_SCALE, "el martillo se ampliaría por encima de @3x");
});

test("4.2.4: subir el ayuntamiento muestra el TH de destino", () => {
  const mini = app.slice(app.indexOf("function miniaturaDe("), app.indexOf("function fichaMejora("));
  assert.match(mini, /town-hall/);
  assert.match(mini, /1000001/);
  assert.match(mini, /toLvl/);
  assert.match(app.slice(app.indexOf("function fichaMejora("), app.indexOf("function tarjetaAhora(")), /miniaturaDe\(paso\)/);
  const hub = app.slice(app.indexOf("function renderPlanHub("), app.indexOf("function renderPlan("));
  assert.match(hub, /thumb\(1000001, \{ size: 44, th \}\)/);
  const manifest = JSON.parse(readFileSync(new URL("../assets/manifest.json", import.meta.url)));
  const hall = manifest.items["1000001"];
  const destino = imageChoice(hall, 12);
  const actual = imageChoice(hall, 11);
  assert.equal(destino.im.ruta, hall.imagenes_por_nivel["12"].ruta);
  assert.equal(destino.im.ruta, "images/townhalls/town-hall-12.png");
  assert.notEqual(destino.im.ruta, actual.im.ruta);
  assert.match(destino.im.origen.fuente, /Fan Kit/);
  assert.equal(destino.im.es_inferior, false);
  assert.equal(imageChoice(hall, 17).im.ruta, "images/townhalls/town-hall-17.png");
  assert.equal(app.includes("imagenes_por_nivel[String(th)]"), false);
});

